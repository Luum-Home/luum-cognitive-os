"""Guard Cognitive OS core against consumer-project vocabulary leakage.

The protected names are NOT written in this file: a public list of the names to
protect is itself the leak, and a plain SHA-256 of a short name is confirmed by
anyone who already suspects it. Each name is stored as
HMAC-SHA256(secret key, lowercased name). Every candidate token of a scanned
file is MACed with the same key and compared (see `term_candidates` and
`fingerprint_term` in scripts/provenance_scan.py). Matching is per token: a
name glued to other letters is not a hit.

The key is read from COS_LEAK_HMAC_KEY or from the key file
(COS_LEAK_HMAC_KEY_FILE, default ~/.config/luum/leak-hmac.key), never from the
repo. Without a key the tests that need it FAIL in CI (CI=true: a gate that
cannot verify must not pass) and are SKIPPED locally with an explicit reason.

The digests below are generated: edit the local list outside the repo
(COS_CONSUMER_TERMS_FILE, default ~/.config/luum/leak-terms.txt) and run
`python3 scripts/leak_terms_hmac.py`. Names in that list are also checked
directly when COS_CONSUMER_TERMS_FILE points to it.
"""

from __future__ import annotations

import base64
import importlib.util
import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
