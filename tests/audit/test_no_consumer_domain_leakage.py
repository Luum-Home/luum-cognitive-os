# One protected name, reversed and base64-encoded so it is not greppable here.
# Chosen on purpose: the least sensitive entry of the list.
ENCODED_PROTECTED_FIXTURE = "b21lZC1rYXZvcnRuZXo="


def _load_scanner():
    spec = importlib.util.spec_from_file_location(
        "provenance_scan_for_leak_audit", ROOT / "scripts" / "provenance_scan.py"
    )
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    # @dataclass resolves annotations through sys.modules[module.__name__].
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


SCANNER = _load_scanner()


def missing_key_outcome(env) -> tuple[str, str]:
    """("fail" | "skip", reason) for a run without the HMAC key."""
    reason = SCANNER.missing_key_message(env)
    if SCANNER.running_in_ci(env):
        return "fail", f"{reason}. CI must provide the secret: without it this gate verifies nothing."
    return "skip", f"{reason}. Protected-name leak check NOT run locally."


def require_leak_key() -> bytes:
    key = SCANNER.load_leak_hmac_key()
    if key is None:
        outcome, reason = missing_key_outcome(os.environ)
        if outcome == "fail":
            pytest.fail(reason, pytrace=False)
        pytest.skip(reason)
    return key


def protected_digests(key: bytes) -> frozenset[str]:
    digests = set(PRIVATE_OR_CONSUMER_TERM_HMAC)
    local = os.environ.get("COS_CONSUMER_TERMS_FILE", "")
    if local and Path(local).is_file():
        for raw in Path(local).read_text(encoding="utf-8").splitlines():
            term = raw.strip()
            # `path:` entries belong to the provenance manifest, not to this check.
            if term and not term.startswith("#") and not term.lower().startswith("path:"):
                digests.add(SCANNER.fingerprint_term(term, key))
    return frozenset(digests)


def decode_fixture(encoded: str) -> str:
    return base64.b64decode(encoded).decode("utf-8")[::-1]


def iter_scanned_files() -> list[Path]:
    files: list[Path] = []
    for relative_root in CORE_PATHS:
        root = ROOT / relative_root
        if not root.exists():
            continue
        for path in root.rglob("*"):
            if not path.is_file():
                continue
            relative = path.relative_to(ROOT).as_posix()
            if IGNORED_PARTS.intersection(path.relative_to(ROOT).parts):
                continue
            if any(relative.startswith(prefix) for prefix in IGNORED_PREFIXES):
                continue
            files.append(path)
    return files


def leaked_terms(text: str, digests: frozenset[str], key: bytes) -> list[str]:
    return SCANNER.hashed_term_hits(text, digests, key)


def test_committed_list_holds_only_digests() -> None:
    assert PRIVATE_OR_CONSUMER_TERM_HMAC, "regenerate with scripts/leak_terms_hmac.py"
    assert all(len(d) == 64 and int(d, 16) >= 0 for d in PRIVATE_OR_CONSUMER_TERM_HMAC)


def test_a_protected_term_is_detected_without_writing_it() -> None:
    key = require_leak_key()
    term = decode_fixture(ENCODED_PROTECTED_FIXTURE)
    assert SCANNER.fingerprint_term(term, key) in PRIVATE_OR_CONSUMER_TERM_HMAC, (
        "the key does not match the committed digests (wrong key, or digests not regenerated)"
    )
    digests = protected_digests(key)

    for text in (
        f"see the {term} integration",
        f"path: services/{term}/main.go",
        f"See The {term.upper()} Integration",
    ):
        assert leaked_terms(text, digests, key) == [term], text

    # Per-token matching: glued to other letters it is a different word.
    assert leaked_terms(f"x{term.replace('-', '')}x", digests, key) == []
    assert leaked_terms("a perfectly generic sentence about gateways", digests, key) == []
    # Keyed: the same name under another key, or a plain SHA-256, does not match.
    assert SCANNER.fingerprint_term(term, key + b"-other") not in PRIVATE_OR_CONSUMER_TERM_HMAC
    import hashlib

    assert hashlib.sha256(term.encode("utf-8")).hexdigest() not in PRIVATE_OR_CONSUMER_TERM_HMAC


def test_core_surfaces_do_not_embed_consumer_private_terms() -> None:
    key = require_leak_key()
    digests = protected_digests(key)
    offenders: list[str] = []
    for path in iter_scanned_files():
        hits = leaked_terms(path.read_text(errors="ignore"), digests, key)
        if hits:
            offenders.append(f"{path.relative_to(ROOT)}: {', '.join(hits)}")

    assert not offenders, "Consumer/private terms leaked into SO core:\n" + "\n".join(offenders)


def _run_without_key(tmp_path: Path, ci: bool) -> subprocess.CompletedProcess[str]:
    env = {k: v for k, v in os.environ.items() if k not in {"COS_LEAK_HMAC_KEY", "CI", "COS_CONSUMER_TERMS_FILE"}}
    env["COS_LEAK_HMAC_KEY_FILE"] = str(tmp_path / "absent.key")
    if ci:
        env["CI"] = "true"
    node = f"{Path(__file__).resolve()}::test_core_surfaces_do_not_embed_consumer_private_terms"
    return subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-rs", "-p", "no:cacheprovider", node],
        cwd=ROOT,
        env=env,
        text=True,
        capture_output=True,
        timeout=120,
        check=False,
    )


def test_missing_key_fails_in_ci_and_skips_locally(tmp_path: Path) -> None:
    assert missing_key_outcome({"CI": "true", "COS_LEAK_HMAC_KEY_FILE": "/nonexistent"})[0] == "fail"
    assert missing_key_outcome({"COS_LEAK_HMAC_KEY_FILE": "/nonexistent"})[0] == "skip"

    in_ci = _run_without_key(tmp_path, ci=True)
    assert in_ci.returncode != 0, in_ci.stdout + in_ci.stderr
    assert "1 failed" in in_ci.stdout and "CI must provide the secret" in in_ci.stdout, in_ci.stdout

    local = _run_without_key(tmp_path, ci=False)
    assert local.returncode == 0, local.stdout + local.stderr
    assert "1 skipped" in local.stdout and "NOT run locally" in local.stdout, local.stdout
